-- Catálogos de FruitScan: tipos enumerados, frutas, clases, umbrales de grado,
-- configuración y fichas agronómicas. Incluye RLS, permisos y datos iniciales.

-- ============ Tipos enumerados ============
create type public.destino as enum (
  'exportacion', 'mercado_nacional', 'procesamiento', 'separar', 'revision_manual'
);
create type public.grado_lote as enum ('A', 'B', 'C', 'rechazo');
create type public.estado_lote as enum ('borrador', 'analizando', 'analizado', 'error');
create type public.origen_sugerencia as enum ('plantilla', 'llm');

-- ============ Función genérica para updated_at ============
create function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Solo la usan los triggers; nadie la llama directamente.
revoke execute on function public.set_updated_at() from public, anon, authenticated;

-- ============ Tablas ============
create table public.frutas (
  id text primary key,
  nombre text not null,
  activa boolean not null default true
);

create table public.clases (
  id integer generated by default as identity primary key,
  fruta_id text not null references public.frutas (id),
  codigo text not null,
  nombre text not null,
  es_sana boolean not null,
  destino_default public.destino not null,
  unique (fruta_id, codigo)
);

create table public.umbrales_grado (
  grado public.grado_lote primary key,
  orden integer not null unique,
  min_pct_sanos numeric(5, 2) not null check (min_pct_sanos between 0 and 100),
  max_pct_separar numeric(5, 2) not null check (max_pct_separar between 0 and 100),
  destino_lote public.destino not null
);

create table public.configuracion (
  clave text primary key,
  valor numeric not null,
  descripcion text
);

-- Se llena a mano por el equipo con fuentes verificadas.
create table public.fichas (
  id integer generated by default as identity primary key,
  clase_id integer not null references public.clases (id),
  causas_posibles text,
  practicas_manejo text,
  fuente_nombre text,
  fuente_url text,
  verificada boolean not null default false,
  updated_at timestamptz not null default now()
);

create index fichas_clase_id_idx on public.fichas (clase_id);

create trigger fichas_set_updated_at
  before update on public.fichas
  for each row execute function public.set_updated_at();

-- ============ RLS: lectura para usuarios autenticados, escritura solo service role ============
alter table public.frutas enable row level security;
alter table public.clases enable row level security;
alter table public.umbrales_grado enable row level security;
alter table public.configuracion enable row level security;
alter table public.fichas enable row level security;

create policy frutas_lectura on public.frutas
  for select to authenticated using (true);
create policy clases_lectura on public.clases
  for select to authenticated using (true);
create policy umbrales_grado_lectura on public.umbrales_grado
  for select to authenticated using (true);
create policy configuracion_lectura on public.configuracion
  for select to authenticated using (true);
create policy fichas_lectura on public.fichas
  for select to authenticated using (true);

-- Los privilegios por defecto del proyecto dan todo a anon y authenticated;
-- los dejamos explícitos: anon nada, authenticated solo lectura.
revoke all on public.frutas, public.clases, public.umbrales_grado, public.configuracion, public.fichas
  from anon, authenticated;
grant select on public.frutas, public.clases, public.umbrales_grado, public.configuracion, public.fichas
  to authenticated;

