-- Inicio de sesión: rol de usuario, catálogo de zonas y perfil de cada usuario.
-- El login (correo y contraseña) lo maneja Supabase Auth; aquí no se guardan
-- contraseñas ni se copian datos de auth.users (como el correo).

-- ============ Rol de usuario ============
-- Por ahora la app solo usa productor.
create type public.rol_usuario as enum ('productor', 'acopio', 'tecnico');

-- ============ Zonas ============
-- Catálogo que llena el equipo. También lo lee anon: el formulario de registro
-- muestra la lista de zonas antes de que el usuario inicie sesión.
create table public.zonas (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  municipio text,
  estado text,
  latitud numeric(9, 6) check (latitud between -90 and 90),
  longitud numeric(9, 6) check (longitud between -180 and 180),
  activa boolean not null default true
);

alter table public.zonas enable row level security;

create policy zonas_lectura on public.zonas
  for select to anon, authenticated using (true);

revoke all on public.zonas from anon, authenticated;
grant select on public.zonas to anon, authenticated;

-- ============ Perfiles ============
-- Un perfil por usuario de auth.users; se borra junto con el usuario.
create table public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre_completo text,
  rol public.rol_usuario not null default 'productor',
  organizacion text,
  zona_id integer references public.zonas (id),
  telefono text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index perfiles_zona_id_idx on public.perfiles (zona_id);

create trigger perfiles_set_updated_at
  before update on public.perfiles
  for each row execute function public.set_updated_at();

alter table public.perfiles enable row level security;

-- Cada usuario ve y edita solo su perfil. No hay políticas de insert ni delete:
-- el perfil lo crea el trigger de registro y se borra en cascada con el usuario.
create policy perfiles_ver_propio on public.perfiles
  for select to authenticated
  using (id = (select auth.uid()));

create policy perfiles_editar_propio on public.perfiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- Permisos por columna: el usuario edita sus datos, pero NO su rol (solo service role).
revoke all on public.perfiles from anon, authenticated;
grant select on public.perfiles to authenticated;
grant update (nombre_completo, organizacion, zona_id, telefono) on public.perfiles to authenticated;

-- ============ Crear el perfil al registrarse ============
-- Toma nombre_completo, organizacion y zona_id de raw_user_meta_data (lo que manda
-- supabase.auth.signUp en options.data). El rol nunca sale de ahí: el usuario puede
-- escribir lo que quiera en su metadata, así que siempre empieza como productor.
-- Si un dato viene vacío o la zona no es válida, queda en null: un error aquí
-- bloquearía el registro del usuario.
create function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_zona_id integer;
begin
  if v_meta ->> 'zona_id' ~ '^[0-9]{1,9}$' then
    select z.id into v_zona_id
    from public.zonas z
    where z.id = (v_meta ->> 'zona_id')::integer and z.activa;
  end if;

  insert into public.perfiles (id, nombre_completo, organizacion, zona_id)
  values (
    new.id,
    nullif(trim(v_meta ->> 'nombre_completo'), ''),
    nullif(trim(v_meta ->> 'organizacion'), ''),
    v_zona_id
  );

  return new;
end;
$$;

revoke execute on function public.crear_perfil_usuario() from public, anon, authenticated;

create trigger crear_perfil_al_registrarse
  after insert on auth.users
  for each row execute function public.crear_perfil_usuario();
